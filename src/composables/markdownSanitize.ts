import DOMPurify, { type Config } from "dompurify";
import { installMathSentinelGuards } from "./markdownMath";

// Math sentinels that leak into attribute values or rawtext containers are
// restored to plain LaTeX source during this pass; see markdownMath.ts.
installMathSentinelGuards(DOMPurify);

const MARKDOWN_SANITIZE_CONFIG: Config = {
  USE_PROFILES: { html: true },
  ALLOW_ARIA_ATTR: true,
  ALLOW_DATA_ATTR: true,
  FORBID_ATTR: ["style"],
  FORBID_TAGS: ["script", "style", "iframe", "object", "embed", "form"],
  ADD_ATTR: ["draggable"],
};

// The html profile drops every SVG element. Reference icons generated by
// markdownInject hold only shape elements and no text, so removing them before
// parsing leaves the output unchanged while DOMPurify no longer builds and
// discards several nodes for every inline reference.
const GENERATED_REF_ICON_RE = /<svg class="md-ref-icon md-ref-icon-lucide[^"]*"[^>]*>[\s\S]*?<\/svg>/g;

// Sanitizing is a pure function of the HTML. Workbench editors remount the
// transcript on every session switch, so the same messages are sanitized again
// and again; their results are reused instead of re-parsing every message.
const SANITIZED_CACHE_MAX_ENTRIES = 1_000;
const SANITIZED_CACHE_MAX_CHARS = 6_000_000;
const sanitizedCache = new Map<string, string>();
let sanitizedCacheChars = 0;

function rememberSanitized(html: string, sanitized: string): void {
  const size = html.length + sanitized.length;
  if (size > SANITIZED_CACHE_MAX_CHARS / 4) return;
  sanitizedCache.set(html, sanitized);
  sanitizedCacheChars += size;
  while (
    sanitizedCache.size > SANITIZED_CACHE_MAX_ENTRIES
    || sanitizedCacheChars > SANITIZED_CACHE_MAX_CHARS
  ) {
    const oldest = sanitizedCache.entries().next().value as [string, string] | undefined;
    if (!oldest) break;
    sanitizedCache.delete(oldest[0]);
    sanitizedCacheChars -= oldest[0].length + oldest[1].length;
  }
}

export function sanitizeRenderedMarkdownHtml(html: string): string {
  if (!html) return "";
  const cached = sanitizedCache.get(html);
  if (cached !== undefined) {
    // Refresh the entry's position for least-recently-used eviction.
    sanitizedCache.delete(html);
    sanitizedCache.set(html, cached);
    return cached;
  }
  const sanitized = DOMPurify.sanitize(
    html.includes("md-ref-icon-lucide") ? html.replace(GENERATED_REF_ICON_RE, "") : html,
    MARKDOWN_SANITIZE_CONFIG,
  );
  rememberSanitized(html, sanitized);
  return sanitized;
}
